"""Glyph atlas for the in-game options overlay (printable ASCII), rendered from Pillow's bundled Aileron font
(public domain). Output: overlay/font.js with `const OV_FONT = {w, h, size, ascent, white: [x, y], glyphs: {code:
[x, y, w, h, xoff, yoff, adv]}, data: '<base64 8-bit alpha>'}`. A 4x4 white block at `white` is used for solid
rectangles so text and boxes share one texture and one draw call.

  python overlay/make_font.py
"""
import base64, json, pathlib
from PIL import Image, ImageDraw, ImageFont

SIZE = 34
font = ImageFont.load_default(size=SIZE)
ascent, descent = font.getmetrics()
W = 512
glyphs, x, y, row_h = {}, 6, 2, 0
cells = []
for code in range(32, 127):
    ch = chr(code)
    l, t, r, b = font.getbbox(ch)
    adv = font.getlength(ch)
    w, h = max(r - l, 0), max(b - t, 0)
    if x + w + 2 > W:
        x, y, row_h = 2, y + row_h + 2, 0
    cells.append((code, ch, x, y, w, h, l, t, adv))
    x += w + 2
    row_h = max(row_h, h)
H = 1
while H < y + row_h + 2:
    H *= 2
img = Image.new('L', (W, H), 0)
d = ImageDraw.Draw(img)
d.rectangle([0, 0, 3, 3], fill=255)                      # white block for solid quads
for code, ch, gx, gy, w, h, l, t, adv in cells:
    if w and h:
        d.text((gx - l, gy - t), ch, font=font, fill=255)
    glyphs[code] = [gx, gy, w, h, l, t, round(adv, 2)]
out = {'w': W, 'h': H, 'size': SIZE, 'ascent': ascent, 'white': [1, 1], 'glyphs': glyphs,
       'data': base64.b64encode(img.tobytes()).decode()}
p = pathlib.Path(__file__).parent / 'font.js'
p.write_text('// Generated by make_font.py from Pillow\'s bundled Aileron font (public domain).\nconst OV_FONT = '
             + json.dumps(out, separators=(',', ':')) + ';\n', encoding='utf-8', newline='\n')
img.save(pathlib.Path(__file__).parent / 'font-preview.png')
print(f'atlas {W}x{H}, {len(glyphs)} glyphs, {p.stat().st_size // 1024} KB')
